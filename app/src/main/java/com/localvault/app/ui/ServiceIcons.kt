/**
 * Picks a logo for a folder from its name ("Steam", "My Discord", "Gmail work" ...). Unknown names
 * get a coloured tile with the folder's first letter.
 */
@Composable
fun FolderIcon(name: String, size: Dp = 40.dp) {
    val brand = remember(name) { ServiceIcons.match(name) }
    val shape = RoundedCornerShape(size * 0.25f)
    when {
        brand != null -> Box(
            modifier = Modifier.size(size).clip(shape).background(brand.background),
            contentAlignment = Alignment.Center,
        ) {
            Icon(
                brand.vector,
                contentDescription = null,
                tint = brand.tint,
                modifier = Modifier.size(size * 0.6f),
            )
        }

        else -> Box(
            modifier = Modifier.size(size).clip(shape).background(ServiceIcons.letterColor(name)),
            contentAlignment = Alignment.Center,
        ) {
            Text(
                name.trim().take(1).uppercase().ifEmpty { "?" },
                color = Color.White,
                fontWeight = FontWeight.Bold,
                fontSize = (size.value * 0.45f).sp,
            )
        }
    }
}

