    fun match(folderName: String): ServiceIcon? {
        val name = folderName.lowercase().trim()
        val words = name.split(Regex("[^a-z0-9.]+")).filter { it.isNotEmpty() }.toSet()
        fun matches(keyword: String) = if (' ' in keyword) name.contains(keyword) else keyword in words || name == keyword

        if (microsoftKeywords.any(::matches)) return microsoft
        val brand = brands.firstOrNull { it.keywords.any(::matches) } ?: return null
        return cache.getOrPut(brand.name) {
            val vector = ImageVector.Builder(brand.name, 24.dp, 24.dp, 24f, 24f)
                .addPath(addPathNodes(brand.path), fill = SolidColor(Color.Black))
                .build()
            ServiceIcon(vector, background = brand.color, tint = Color.White)
        }
    }

    fun letterColor(folderName: String): Color =
        letterColors[Math.floorMod(folderName.trim().lowercase().hashCode(), letterColors.size)]
